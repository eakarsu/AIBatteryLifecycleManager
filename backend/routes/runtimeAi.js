'use strict';
const express = require('express');
const pool = require('../config/database');
const { authenticateToken } = require('../middleware/auth');
const { createLifecycleReadinessHandlers } = require('../services/runtimeReadiness');
const router = express.Router();
const readiness = createLifecycleReadinessHandlers({ pool });
router.post('/lifecycle-readiness', authenticateToken, readiness.generate);
router.get('/lifecycle-readiness/history', authenticateToken, readiness.history);
module.exports = router;
